/* USER CODE BEGIN 1 */
void USART1_IRQHandler(void)
{
    if (__HAL_UART_GET_FLAG(&huart1, UART_FLAG_IDLE))
    {
        __HAL_UART_CLEAR_FLAG(&huart1, UART_CLEAR_IDLEF);

        uint16_t pos = CMD_BUFFER_SIZE - __HAL_DMA_GET_COUNTER(huart1.hdmarx);

        if (pos != old_pos)
        {
            uint16_t len;

            if (pos > old_pos)
                len = pos - old_pos;
            else
                len = CMD_BUFFER_SIZE - old_pos;

            memcpy(command_buffer, &uart_rx_dma_buffer[old_pos], len);
            command_buffer[len] = '\0';

            old_pos = pos;

            // -------------------------
            // COMMAND PARSING QUI
            // -------------------------

            if (strncmp(command_buffer, "start", 5) == 0)
            {
                acq_enabled = 0;
                HAL_TIM_PWM_Stop(&htim3, TIM_CHANNEL_2);
                HAL_SPI_DMAStop(&hspi1);

                
                parse_start_command(command_buffer);
                

                acq_enabled = 1;
                delay_counter = 0;
                HAL_GPIO_WritePin(GPIOD, GPIO_PIN_11, GPIO_PIN_RESET);
                HAL_NVIC_EnableIRQ(TIM2_IRQn);
                HAL_TIM_Base_Start_IT(&htim2);
            }
            else if (strncmp(command_buffer, "stop", 4) == 0)
            {
                acq_enabled = 0;
                HAL_TIM_PWM_Stop(&htim3, TIM_CHANNEL_2);
                HAL_SPI_DMAStop(&hspi1);
            }
            else if (strncmp(command_buffer, "set,", 4) == 0)
            {
                acq_enabled = 0;
                HAL_TIM_PWM_Stop(&htim3, TIM_CHANNEL_2);
                HAL_SPI_DMAStop(&hspi1);

                parse_configuration_command(command_buffer);
            }
            else if (strncmp(command_buffer, "rd", 2) == 0)
            {
                acq_enabled = 0;
                HAL_TIM_PWM_Stop(&htim3, TIM_CHANNEL_2);
                HAL_SPI_DMAStop(&hspi1);

                parse_resetDefault_command(command_buffer);
            }
            else if (strncmp(command_buffer, "r", 1) == 0)
            {
                acq_enabled = 0;
                HAL_TIM_PWM_Stop(&htim3, TIM_CHANNEL_2);
                HAL_SPI_DMAStop(&hspi1);

                parse_reset_command(command_buffer);
            }
        }
    }

    HAL_UART_IRQHandler(&huart1);
}
